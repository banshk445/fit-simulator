// GarmentCloth(메인 스레드, 지오메트리/입력 처리)와 clothWorker(물리 연산)
// 양쪽이 동일한 값을 봐야 하므로 한 곳에 모아둔다.
//
// 실제 마네킹 메시(Xbot, BVH) + 자체충돌 기반 아키텍처. 오늘 한때 "웹
// 최적화 게임형"으로 캡슐 2개짜리 근사 충돌 + 자체충돌 끄기로 전면
// 개편했었는데, 캡슐은 완벽한 원통이라 옷이 매끈한 튜브/판초처럼 보이고
// 실제 몸 굴곡을 못 따라가는 근본적 한계가 있었다(실측 확인 — "옷을 입은
// 게 아니라 그냥 걸친 느낌"). CLO3D에 준하는 자연스러운 드레이핑을
// 위해서는 실제 몸 곡면과 자체 접힘/주름이 필요해 다시 이 구조로
// 돌아왔다. 캡슐(torsoCapsule.ts)은 완전히 버리지 않고, BVH가 탐지 반경
// 밖으로 놓쳐 파티클이 몸속에 갇히는 것을 구조하는 보조 안전망으로만
// 남겨둔다.

// 46번(전면 재설계 — 통합 단일 패널): 사용자가 "소매를 별도 원통으로
// 만들지 말고 몸판과 이어진 하나의 넓은 천으로 만들어 달라"고 명시적으로
// 요청했다(AskUserQuestion으로 위험을 설명하고 확답을 받음). 기존에는
// 몸판(앞/뒤)과 소매(좌/우)가 별개 패널이라 그 경계(암홀 시접)가 아무리
// 다듬어도 완전히 안 감춰졌는데, 이제 앞판/뒤판 자체를 어깨 폭보다 훨씬
// 넓게(소매 끝까지 닿도록) 만들어 소매를 "같은 천의 연장"으로 만든다 —
// buildGarmentSim.ts의 layoutTorsoPanels 재작성 참고. 그만큼 가로(COLS)
// 해상도도 더 필요해(같은 열 개수로 훨씬 넓은 폭을 표현해야 목선 곡선이
// 다시 성기게 보이지 않도록) 30→44로 올렸다.
//
// 46번 실측(추가 — 각진 갑옷 모양): 목선 찢어짐을 고친 뒤 실측(스크린샷)
// 해보니, 소매 구간이 큰 평평한 삼각형 몇 개로만 이뤄져 있어 각지고
// 뻣뻣한 "갑옷 어깨보호구"처럼 보였다 — 목표 지점 자체의 매끄러움
// (smoothstep)을 고쳐도 크게 나아지지 않아, 파라미터 문제가 아니라
// 이 구간의 정점 밀도(=삼각형 크기) 자체가 부족한 게 근본 원인으로
// 보였다. 사용자가 "소매 구간 해상도 증가"를 명시적으로 선택했다 —
// COLS/ROWS를 함께 올려(가로세로 비율 유지) 격자를 촘촘하게 한다.
// ARM_ROWS(아래)도 같은 비율로 같이 올려야 소매가 차지하는 "실제 키
// 대비 세로 구간"이 늘어나지 않고 그대로 유지된다(그냥 더 촘촘해질
// 뿐). 입자 수가 늘어난 만큼(약 1.75배) 물리 비용도 늘어나므로, 실측
// (프레임/워커 지연)으로 문제가 없는지 확인이 필요하다.
export const COLS = 60;
export const ROWS = 36;
export const PARTICLES_PER_PANEL = COLS * ROWS;

// 46번(전면 재설계): 소매가 더 이상 별도 패널이 아니므로 몸판(앞/뒤) 2개
// 패널만 남는다.
export const PANEL_FRONT = 0;
export const PANEL_BACK = 1;

// 46번: 0번 행(어깨선) 중 이 비율(중심 기준 절반 폭 대비) 안쪽만 몸/목선에
// 고정(pin)한다 — 그 바깥(소매 쪽으로 뻗은 부분)은 사용자 요청대로 핀을
// 완전히 풀어 중력만 받게 한다. 기존 어깨 핀 폭(SHOULDER_PIN_OUTSET 등
// 반영된 실제 어깨너비)과 맞아떨어지도록 layoutTorsoPanels가 계산하는
// "어깨 실측 반폭 / 전체 반폭" 비율을 그대로 쓴다 — 고정값이 아니라
// buildGarmentSim.ts에서 동적으로 계산된다(TORSO_PIN_FRACTION은 그
// 계산에 쓰는 게 아니라 참고용 문서화 상수일 뿐, 실제로는 shoulderHalfWidth
// 값 자체를 기준으로 판별한다).
// 46번 실측(해상도 증가에 맞춰 비례 조정): ROWS를 28→36으로 올린 만큼
// (36/28≈1.29배) 이 값도 같이 올리지 않으면 소매 구간이 차지하는 실제
// 키 대비 세로 폭이 줄어들어 버린다 — 9 * 36/28 ≈ 11.6, 반올림해 12.
export const ARM_ROWS = 12;

export const SUBSTEP_DT = 1 / 60;
// 워커가 한 번에 몰아서 따라잡을 수 있는 서브스텝 상한. 너무 크게 잡으면
// 워커 자신이 느려졌을 때 처리 시간이 계속 늘어나는 악순환에 빠진다.
export const MAX_SUBSTEPS = 2;

export const GRAVITY_BASE: readonly [number, number, number] = [0, -2.2, 0];

// 메시 충돌 검사(BVH closestPointToPoint)는 구체/캡슐보다 비싸서, 매
// 반복이 아니라 3번째 반복마다(+ 마지막 반복엔 항상) 수행한다.
export const COLLISION_EVERY = 3;
// 표면에서 얼마나 떨어뜨려 놓을지(옷감 두께 근사치) — BVH 밀어내는 거리.
export const COLLISION_MARGIN = 0.015;
// BVH closestPointToPoint의 maxThreshold(탐지 반경). COLLISION_MARGIN과
// 분리해 넉넉하게 잡는다 — closestPointToPoint는 maxThreshold보다 먼
// 표면점은 "못 찾은 것"으로 취급해 파티클이 전혀 밀려나지 못하므로,
// 제약/중력이 한 서브스텝 만에 margin 밖으로 밀어넣은 파티클도 다음
// 충돌 검사에서 다시 붙잡아 표면 밖으로 구해낼 여유가 필요하다.
// bvhFromArrays.ts의 PUSH_RELAXATION(under-relaxation)과 짝을 이루는
// 값이라, 탐지 반경을 넓게 잡아도 한 번에 확 스냅되지 않고 여러 반복에
// 걸쳐 서서히 끌려오므로 구조 제약이 저항할 시간을 번다.
export const COLLISION_DETECTION_RADIUS = 0.15;
// 한 서브스텝 동안 파티클이 이동할 수 있는 최대 거리. 충돌 노멀이 절단면
// 근처에서 튀거나 제약끼리 힘겨루기를 해도, 이 이상 한 번에 움직이지
// 못하게 강제로 잘라내(clamp) 순간적인 반발력으로 옷감이 찢어지듯 튀는
// 현상을 막는 안전장치. 60fps 기준 5cm/프레임은 초속 3m로, 정상적인
// 처짐 속도보다 훨씬 빨라 진짜 발산 상황만 걸러낸다.
export const MAX_DISPLACEMENT_PER_SUBSTEP = 0.05;
// 앞판/뒤판 파티클끼리 이보다 가까워지면 밀어낸다. 옆선 시접(SEAM_REST_LENGTH)
// 보다 반드시 작아야 시접 제약과 자체충돌이 서로 힘겨루기를 하지 않는다.
export const SELF_COLLISION_MIN_DIST = 0.004;
// 옆선(사이드심) 시접의 목표 간격.
export const SEAM_REST_LENGTH = 0.006;
// 겨드랑이 밑부터 밑단까지만 옆선을 잇고, 그 위(어깨~겨드랑이)는 트여 있는
// 암홀(진동)로 남겨둔다 — 별도 소매 패널 없이도 최소한의 팔 통로를 만든다.
// 이 구간이 넓을수록 앞/뒤판이 서로 안 붙잡아 주는 구간도 넓어져서, 뒤판이
// 중력만으로 몸통에서 옆으로 벌어져 뻣뻣한 판처럼 떠 보이는 문제가 실측으로
// 확인됐다 — 실제 티셔츠 암홀 깊이 근사치보다 조금 타이트하게 잡아 상체
// 위쪽에서도 앞뒤가 서로 붙들어 주게 한다. (테이퍼 구간을 늘려 오프숄더
// 처짐을 완화해보려 했지만 실측상 효과가 없어 원래 값으로 되돌렸다 — 단,
// 그때는 halfWidthAtRow의 클램프 버그(buildGarmentSim.ts 참고, shoulderHalfWidth를
// fullHalfWidth로 항상 깎아버리던 버그)가 아직 안 고쳐진 상태라 테이퍼 구간을
// 늘려도 애초에 늘어날 폭 자체가 없었다 — 이번엔 그 클램프를 먼저 없앤 뒤
// 다시 실측해, 몸판 바깥쪽 열이 짧은 소매 이음매 링에서 얼마나 떨어져
// 있는지(Playwright evaluate로 두 메시의 실제 정점 좌표 직접 대조) 재보니
